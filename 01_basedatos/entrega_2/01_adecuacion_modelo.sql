-- 2. TABLA TEMPORAL PARA RESPALDAR TARIFAS BASE POR HABITACIÓN
CREATE TABLE TMP_TARIFAS_HABITACION AS
SELECT 
    h.id_habitacion,
    NVL(ROUND(AVG(CASE WHEN t.id_temporada IN (1, 5, 9) THEN t.precio_noche END), -3), 
        ROUND(DBMS_RANDOM.VALUE(120000, 250000), -3)) AS tarifa_baja,
    NVL(ROUND(AVG(CASE WHEN t.id_temporada NOT IN (1, 5, 9) THEN t.precio_noche END), -3), 
        ROUND(DBMS_RANDOM.VALUE(280000, 480000), -3)) AS tarifa_alta_base
FROM HABITACION h
LEFT JOIN TARIFA t ON h.id_habitacion = t.id_habitacion
GROUP BY h.id_habitacion;

