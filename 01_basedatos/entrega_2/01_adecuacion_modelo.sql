-- 4. RECREACIÓN DE TABLA TARIFA CON LAS 2 TEMPORADAS
CREATE TABLE TARIFA (
    ID_TARIFA      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PRECIO_NOCHE   NUMBER(12,2) NOT NULL,
    ID_TEMPORADA   NUMBER NOT NULL,
    ID_HABITACION  NUMBER NOT NULL,
    CONSTRAINT FK_TARIFA_TEMPORADA FOREIGN KEY (ID_TEMPORADA) 
        REFERENCES TEMPORADA(ID_TEMPORADA),
    CONSTRAINT FK_TARIFA_HABITACION FOREIGN KEY (ID_HABITACION) 
        REFERENCES HABITACION(ID_HABITACION),
    CONSTRAINT UK_TARIFA_HAB_TEMP UNIQUE (ID_HABITACION, ID_TEMPORADA),
    CONSTRAINT CHK_TARIFA_PRECIO CHECK (PRECIO_NOCHE > 0)
);

-- Inserción de las tarifas: Tarifa Baja y Tarifa Alta para cada una de las 400 habitaciones
-- Asegurando que la tarifa alta sea superior a la tarifa baja
INSERT INTO TARIFA (PRECIO_NOCHE, ID_TEMPORADA, ID_HABITACION)
SELECT 
    tarifa_baja,
    1,
    id_habitacion
FROM TMP_TARIFAS_HABITACION;

INSERT INTO TARIFA (PRECIO_NOCHE, ID_TEMPORADA, ID_HABITACION)
SELECT 
    GREATEST(tarifa_alta_base, ROUND(tarifa_baja * 1.40, -3)),
    2,
    id_habitacion
FROM TMP_TARIFAS_HABITACION;

